/**
 * Writes supabase/seed/catalogue.sql from buildCatalogue — the same rows `POST /api/catalogue/seed` upserts.
 * Run: pnpm db:catalogue:generate
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import type { ICatalogueSeedEntry } from '../../../server/controllers/catalogue/buildCatalogue/buildCatalogue'
import { buildCatalogue } from '../../../server/controllers/catalogue/buildCatalogue/buildCatalogue'
import { CITIES } from '../../../server/controllers/catalogue/buildCatalogue/catalogueCities'

const OUT_FILE = fileURLToPath(new URL('../catalogue.sql', import.meta.url))

const rows = buildCatalogue()

const sqlText = (value: string) => `'${value.replaceAll('\'', '\'\'')}'`
const sqlValue = (row: ICatalogueSeedEntry) => [
  sqlText(row.ref),
  sqlText(row.kind),
  String(row.cityId),
  sqlText(row.cityName),
  sqlText(row.name),
  sqlText(row.description),
  row.priceAmount === null ? 'null' : String(row.priceAmount),
  row.priceCurrency === null ? 'null' : sqlText(row.priceCurrency),
  row.priceUnit === null ? 'null' : sqlText(row.priceUnit),
  `${sqlText(JSON.stringify(row.attributes))}::jsonb`
].join(', ')

const BATCH = 500
const statements: string[] = []
for (let start = 0; start < rows.length; start += BATCH) {
  statements.push(
    'insert into public.catalogue_entries (ref, kind, city_id, city_name, name, description, price_amount, price_currency, price_unit, attributes) values\n' +
    rows.slice(start, start + BATCH).map(row => `  (${sqlValue(row)})`).join(',\n') +
    ';'
  )
}

const kinds = Map.groupBy(rows, row => row.kind)
writeFileSync(OUT_FILE, [
  '-- Generated by supabase/seed/catalogue/generate-catalogue.ts (pnpm db:catalogue:generate). Do not edit by hand.',
  `-- ${rows.length} entries in ${CITIES.length} cities: ${kinds.get('transport')?.length} transport, ${kinds.get('stay')?.length} stays, ${kinds.get('place')?.length} places.`,
  '-- City ids are GeoNames ids (= TCity.id). Reykjavik has no rows on purpose: a request there fails.',
  '',
  statements.join('\n\n'),
  ''
].join('\n'))

console.info(`catalogue.sql: ${rows.length} entries (${kinds.get('transport')?.length} transport) in ${CITIES.length} cities`)
